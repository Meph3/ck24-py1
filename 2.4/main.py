from abc import ABC, abstractmethod


class УчебноеЗаведение(ABC):

    def __init__(self, название: str, адрес: str, количество_студентов: int) -> None:

        self._название = название  # Инкапсуляция: защищённый атрибут, т.к. изменяется только внутри класса
        self._адрес = адрес  # Аналогично
        self.количество_студентов = количество_студентов

    def __str__(self) -> str:

        return f"{self._название} ({self._адрес})"

    def __repr__(self) -> str:

        return f"УчебноеЗаведение(название={self._название}, адрес={self._адрес}, количество_студентов={self.количество_студентов})"

    @abstractmethod
    def получить_информацию(self) -> str:

        pass

class Школа(УчебноеЗаведение):

    def __init__(self, название: str, адрес: str, количество_студентов: int, количество_классов: int) -> None:

        super().__init__(название, адрес, количество_студентов)
        self.количество_классов = количество_классов

    def __str__(self) -> str:

        return f"Школа {self._название} ({self._адрес}), классов: {self.количество_классов}"

    def получить_информацию(self) -> str:

        return f"Школа {self._название} имеет {self.количество_классов} классов и {self.количество_студентов} учеников."

class Университет(УчебноеЗаведение):

    def __init__(self, название: str, адрес: str, количество_студентов: int, количество_факультетов: int) -> None:

        super().__init__(название, адрес, количество_студентов)
        self.количество_факультетов = количество_факультетов

    def __str__(self) -> str:

        return f"Университет {self._название} ({self._адрес}), факультетов: {self.количество_факультетов}"

    def получить_информацию(self) -> str:

        return f"Университет {self._название} имеет {self.количество_факультетов} факультетов и {self.количество_студентов} студентов."

# Примеры использования:
школа = Школа("Гимназия №1", "ул. Пушкина, 10", 500, 25)
университет = Университет("МГУ", "Ленинские горы, 1", 30000, 15)

print(школа)
print(университет)
print(школа.получить_информацию())
print(университет.получить_информацию())
